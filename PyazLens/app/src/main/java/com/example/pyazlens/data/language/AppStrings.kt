    fun getStrings(langCode: String): UiStrings {
        return if (langCode == LanguageManager.LANG_HINDI || langCode == "Hindi" || langCode == "हिंदी") Hindi else English
    }

    fun translateDefect(defectName: String, strings: UiStrings): String {
        return when {
            defectName.equals("Rotten", ignoreCase = true) -> strings.defectRotten
            defectName.equals("Cut/Crack", ignoreCase = true) || defectName.equals("Cut / Crack", ignoreCase = true) -> strings.defectCutCrack
            defectName.equals("Sprouted", ignoreCase = true) -> strings.defectSprouted
            defectName.equals("Skin Damage", ignoreCase = true) || defectName.equals("SkinDamaged", ignoreCase = true) -> strings.defectSkinDamage
            defectName.equals("Sunburned", ignoreCase = true) -> strings.defectSunburned
            defectName.equals("Misshapen", ignoreCase = true) -> strings.defectMisshapen
            defectName.equals("No Defect", ignoreCase = true) -> strings.defectNoDefect
            else -> defectName
        }
    }

    fun translateGrade(gradeName: String, strings: UiStrings): String {
        val clean = gradeName.uppercase().replace("GRADE ", "").trim()
        return when (clean) {
            "A" -> strings.gradeA
            "URS" -> strings.gradeUrs
            "REJECT", "REJECTED" -> strings.gradeReject
            else -> gradeName
        }
    }
